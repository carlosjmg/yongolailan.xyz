/** Normalise a platform name so "Apple Music", "apple-music" etc. all match. */
function keyFor(name: string): string | null {
  const n = name.toLowerCase().replace(/[^a-z]/g, "");
  if (n.includes("youtubemusic") || n === "ytmusic" || n === "ytm") return "youtubemusic";
  if (n.includes("youtube") || n === "yt") return "youtube";
  if (n.includes("spotify")) return "spotify";
  if (n.includes("apple") || n === "itunes") return "apple";
  if (n.includes("soundcloud") || n === "sc") return "soundcloud";
  if (n.includes("instagram") || n === "ig") return "instagram";
  if (n.includes("tiktok")) return "tiktok";
  if (n.includes("twitter") || n === "x") return "x";
  if (n.includes("bandcamp") || n === "bc") return "bandcamp";
  if (n.includes("tidal")) return "tidal";
  if (n.includes("deezer")) return "deezer";
  if (n.includes("vimeo")) return "vimeo";
  if (n.includes("facebook") || n === "fb") return "facebook";
  return null;
}

export function hasPlatformIcon(name: string): boolean {
  return keyFor(name) !== null;
}

export default function PlatformIcon({ name, size = 20 }: { name: string; size?: number }) {
  const key = keyFor(name);
  if (!key) {
    // No brand glyph — show the name so nothing ever renders blank.
    return (
      <span
        style={{
          fontFamily: "var(--font-mono)",
          fontSize: "10px",
          letterSpacing: "0.1em",
          textTransform: "uppercase",
        }}
      >
        {name}
      </span>
    );
  }
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="currentColor"
      role="img"
      aria-label={name}
      style={{ display: "block", flexShrink: 0 }}
    >
      {paths[key]({ size })}
    </svg>
  );
}
